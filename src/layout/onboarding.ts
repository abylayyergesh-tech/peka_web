/** v2: тур стал главами. Прежняя отметка «видел» (v1) относилась к короткому
 *  обзору — новый обзор покажется каждому ещё раз, один раз. */
export const tourStorageKey = (identity: string) => `peka-web:onboarding:v2:${identity}`;

export interface TourListItem { label: string; hint: string }

export interface TourStep {
  title: string;
  /** Основной абзац. */
  text?: string;
  /** «Что здесь есть»: название — пояснение. */
  items?: TourListItem[];
  /** Пошаговая инструкция. */
  howto?: string[];
  /** Совет или предупреждение под инструкцией. */
  tip?: string;
  /** Что подсветить. Без него (и без `section`) шаг — по центру экрана. */
  selector?: string;
  /** Раскрыть этот раздел меню и подсветить его целиком. */
  section?: string;
  /** Пункты меню, которые выделяются внутри раскрытого раздела. */
  spot?: string[];
  /** Кнопка «Открыть …»: закончить тур и перейти на экран. */
  link?: { path: string; label: string };
  /** Кнопка «Все главы» — на последнем шаге обзора. */
  showChapters?: boolean;
}

export interface TourChapter {
  key: string;
  title: string;
  summary: string;
  steps: TourStep[];
}

