function sectionChapters(section: NavSection): TourChapter[] {
  const guide = SECTION_GUIDES[section.key];
  const visible = new Map(section.items.map((i) => [i.path, i]));

  const groups = guide ? [...guide.groups] : [];
  // Пункт меню, не разложенный по группам (новый экран), не должен пропасть
  // из тура — он уходит в «Ещё».
  const grouped = new Set(groups.flatMap((g) => g.paths));
  const rest = section.items.filter((i) => !grouped.has(i.path)).map((i) => i.path);
  if (rest.length) groups.push({ title: guide ? "Ещё" : section.label, paths: rest });

  const chapters: { group: string; chapter: TourChapter }[] = [];
  groups.forEach((group, index) => {
    const items = group.paths.map((p) => visible.get(p)).filter((i): i is NavItem => !!i);
    if (!items.length) return;
    const text = [chapters.length === 0 ? guide?.summary : undefined, group.intro]
      .filter(Boolean).join(" ");
    const steps: TourStep[] = [{
      title: group.title,
      text: text || undefined,
      section: section.key,
      spot: items.map((i) => i.path),
      items: items.map((i) => ({ label: i.label, hint: ITEM_HINTS[i.path] ?? "" })),
    }];
    for (const flow of guide?.workflows ?? []) {
      const item = visible.get(flow.path);
      if (!item || !group.paths.includes(flow.path)) continue;
      steps.push({
        title: `Как: ${flow.title.charAt(0).toLowerCase()}${flow.title.slice(1)}`,
        howto: flow.howto,
        tip: flow.tip,
        section: section.key,
        spot: [flow.path],
        link: { path: flow.path, label: item.label },
      });
    }
    chapters.push({ group: group.title, chapter: {
      // Ключ — по месту группы в описании раздела, а не среди видимых: отметка
      // «пройдена» не должна переезжать на другую главу при смене прав.
      key: groups.length === 1 ? section.key : `${section.key}:${index}`,
      title: section.label,
      summary: items.map((i) => i.label).join(", "),
      steps,
    } });
  });

  if (chapters.length === 1) {
    const { chapter } = chapters[0];
    return [{ ...chapter, summary: guide?.summary ?? chapter.summary }];
  }
  return chapters.map(({ group, chapter }) => ({ ...chapter, title: `${section.label}: ${group}` }));
}

/** Все главы, доступные участнику с этими разделами меню: обзор, общие
 *  приёмы и главы по группам экранов каждого видимого раздела. */
export function tourChapters(sections: NavSection[]): TourChapter[] {
  return [
    overviewChapter(sections),
    LISTS_CHAPTER,
    ...sections.flatMap(sectionChapters),
  ];
}

/** «1 шаг», «3 шага», «12 шагов». */
export function stepsLabel(n: number): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  const word = mod10 === 1 && mod100 !== 11 ? "шаг"
    : mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14) ? "шага"
      : "шагов";
  return `${n} ${word}`;
}

// --------------------------------------------------------------- прогресс

/** `seen` — обзор уже показывался (досмотрен или закрыт): сам больше не
 *  открывается. `done` — главы, пройденные до конца: галочка в оглавлении. */
export interface TourProgress { seen: boolean; done: string[] }

// Если хранилище недоступно (приватный режим), прогресс живёт до перезагрузки.
const memory = new Map<string, TourProgress>();

export function readProgress(key: string): TourProgress {
  const kept = memory.get(key);
  if (kept) return kept;
  try {
    const raw = localStorage.getItem(key);
    if (raw) {
      const parsed = JSON.parse(raw) as Partial<TourProgress>;
      return { seen: !!parsed.seen, done: Array.isArray(parsed.done) ? parsed.done : [] };
    }
  } catch {
    /* битая запись или нет хранилища — как будто тура не было */
  }
  return { seen: false, done: [] };
}

export function saveProgress(key: string, progress: TourProgress): void {
  memory.set(key, progress);
  try {
    localStorage.setItem(key, JSON.stringify(progress));
  } catch {
    /* остаётся в памяти */
  }
}
